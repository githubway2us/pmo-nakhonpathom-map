/* =========================================================
   Escape ข้อความก่อนฝังลง HTML กัน markup พัง
========================================================= */

const escHTML = s =>
  String(s).replace(/[&<>"']/g, c =>
    ({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c]));

/* =========================================================
   สร้าง Dropdown ตำแหน่ง/สังกัด
   fillAffiliation(selectElement, showPlaceholder)
========================================================= */

window.fillAffiliation = (sel, placeholder) => {

  if (!sel) return;

  let html = '';

  if (placeholder) {
    html += '<option value="">— กรุณาเลือกตำแหน่ง/สังกัด —</option>';
  }

  html += AFFILIATIONS
    .map(([group, list]) =>
      '<optgroup label="' + escHTML(group) + '">' +

      list.map(value => {
        const label = value === 'other' ? 'อื่น ๆ' : value;
        return '<option value="' + escHTML(value) + '">' +
               escHTML(label) + '</option>';
      }).join('') +

      '</optgroup>'
    )
    .join('');

  sel.innerHTML = html;
};

/* =========================================================
   ผูกฟิลด์ "อื่น ๆ" — แสดง/ซ่อน + required อัตโนมัติ
   wireAffiliationOther(select, otherWrapper, otherInput)
   คืนฟังก์ชัน sync() ไว้เรียกบังคับอัปเดต (เช่น หลัง form.reset())
========================================================= */

window.wireAffiliationOther = (sel, otherWrap, otherInput) => {

  if (!sel || !otherWrap) return null;

  const sync = () => {
    const isOther = sel.value === 'other';
    otherWrap.style.display = isOther ? '' : 'none';
    if (otherInput) {
      otherInput.required = isOther;
      if (!isOther) otherInput.value = '';
    }
  };

  sel.addEventListener('change', sync);
  sync(); /* จัดสถานะเริ่มต้นให้ตรงกับค่าปัจจุบัน */

  return sync;
};

/* หน้าแก้ไขโปรไฟล์ (ถ้ามี select id="pAff") */
(() => {
  const s = document.getElementById('pAff');
  if (s) fillAffiliation(s, false);
})();